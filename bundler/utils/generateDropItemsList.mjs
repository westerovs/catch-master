import fs from 'fs'
import path from 'path'
import {fileURLToPath} from 'url'
import {format, resolveConfig} from 'prettier'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '../..')

const DROP_ITEMS_DIR = path.resolve(rootDir, 'raw-assets/ui/levelUi{m}{tps}/drop-items')
const OUTPUT_FILE = path.resolve(rootDir, 'src/game/generatedAssets/dropItemsList.ts')
const IMAGE_EXTENSIONS = ['.png', '.webp', '.jpg', '.jpeg']

// Проверяет, что файл является изображением.
const isImageFile = (fileName) => {
  const extension = path.extname(fileName).toLowerCase()
  return IMAGE_EXTENSIONS.includes(extension)
}

// Собирает имена texture alias из папки с исходниками.
const collectDropItemNames = () => {
  if (!fs.existsSync(DROP_ITEMS_DIR)) {
    console.error('[generateDropItemsList]: drop-items directory is missing')
    return []
  }
  
  const itemNames = fs
    .readdirSync(DROP_ITEMS_DIR, {withFileTypes: true})
    .filter((entry) => entry.isFile() && isImageFile(entry.name))
    .map((entry) => path.parse(entry.name).name)
  
  return [...new Set(itemNames)].sort((firstName, secondName) => firstName.localeCompare(secondName))
}

// Создаёт содержимое генерируемого файла.
const createDropItemsListContent = (itemNames) => {
  return `// AUTOGENERATED FILE. DO NOT EDIT

const DROP_ITEMS_LIST = ${JSON.stringify(itemNames, null, 2)} as const

type DropItemName = (typeof DROP_ITEMS_LIST)[number]

export {
  DROP_ITEMS_LIST,
}

export type {
  DropItemName,
}
`
}

// Записывает сгенерированный файл.
const writeGeneratedFile = (content) => {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), {recursive: true})
  fs.writeFileSync(OUTPUT_FILE, content)
}

// Генерирует список доступных items.
const generateDropItemsList = async () => {
  const itemNames = collectDropItemNames()
  const content = createDropItemsListContent(itemNames)
  const prettierConfig = await resolveConfig(OUTPUT_FILE)
  const formattedContent = await format(content, {...prettierConfig, filepath: OUTPUT_FILE})
  
  writeGeneratedFile(formattedContent)
  console.log(`AUTOGENERATED DROP ITEMS LIST: ${itemNames.length}`)
}

export {
  generateDropItemsList,
}
