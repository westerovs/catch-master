import fs from 'fs'
import path from 'path'
import {fileURLToPath} from 'url'
import {format, resolveConfig} from 'prettier'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '../..')

const AUDIO_DIR = path.resolve(rootDir, 'public/assets/audio')
const MUSIC_PLAYER_DIR = path.resolve(AUDIO_DIR, 'music/level-music')
const SFX_DIR = path.resolve(AUDIO_DIR, 'sfx')
const OUTPUT_FILE = path.resolve(rootDir, 'src/game/generatedAssets/soundList.ts')
const AUDIO_EXTENSIONS = ['.mp3', '.ogg']

// проверяет, что файл является аудио
const isAudioFile = (name) => {
  const ext = path.extname(name).toLowerCase()
  return AUDIO_EXTENSIONS.includes(ext)
}

// возвращает список аудиофайлов из директории и всех её вложенных директорий
const listAudioFilesRecursively = (rootDirAbs, currentDirAbs = rootDirAbs) => {
  if (!fs.existsSync(currentDirAbs)) return []

  return fs
    .readdirSync(currentDirAbs, {withFileTypes: true})
    .flatMap((entry) => {
      const entryAbs = path.resolve(currentDirAbs, entry.name)

      if (entry.isDirectory()) {
        return listAudioFilesRecursively(rootDirAbs, entryAbs)
      }

      if (!entry.isFile() || !isAudioFile(entry.name)) return []

      return path.relative(rootDirAbs, entryAbs).split(path.sep).join('/')
    })
    .sort((a, b) => a.localeCompare(b))
}

// собирает данные для генерации soundList
const collectSoundData = () => {
  const musicPlayerFiles = listAudioFilesRecursively(MUSIC_PLAYER_DIR)
  const sfxFiles = listAudioFilesRecursively(SFX_DIR)

  return {
    musicPlayerFiles,
    sfxFiles,
  }
}

// создаёт содержимое генерируемого soundList файла
const createSoundListContent = ({musicPlayerFiles, sfxFiles}) => {
  return `// AUTOGENERATED FILE. DO NOT EDIT
type MusicPlayerListOptions = {
  basePath?: string
}

type MusicPlayerPlaylist = Record<string, {
  alias: string
  src: string
}>

const MUSIC_PLAYER_FILES: string[] = ${JSON.stringify(musicPlayerFiles, null, 2)}
const SFX_FILES: string[] = ${JSON.stringify(sfxFiles, null, 2)}

const toAlias = (fileName: string) => {
  const slashIndex = fileName.lastIndexOf('/')
  const dotIndex = fileName.lastIndexOf('.')
  const endIndex = dotIndex === -1 ? fileName.length : dotIndex

  return fileName.slice(slashIndex + 1, endIndex)
}

const createMusicPlayerPlaylist = ({basePath = ''}: MusicPlayerListOptions = {}): MusicPlayerPlaylist => Object.fromEntries(
  MUSIC_PLAYER_FILES.map((fileName) => {
    const alias = toAlias(fileName)

    return [alias, {
      alias,
      src: basePath + 'assets/audio/music/level-music/' + fileName
    }]
  })
)

const MUSIC_PLAYER_PLAYLIST = createMusicPlayerPlaylist()
const MUSIC_PLAYER_ALIASES = Object.keys(MUSIC_PLAYER_PLAYLIST)
const SFX_ALIASES = SFX_FILES.map(toAlias)

const createSfxList = () => SFX_FILES.map((fileName) => ({
  alias: toAlias(fileName),
  src: 'assets/audio/sfx/' + fileName
}))

export {
  createMusicPlayerPlaylist,
  createSfxList,
  MUSIC_PLAYER_ALIASES,
  MUSIC_PLAYER_FILES,
  MUSIC_PLAYER_PLAYLIST,
  SFX_ALIASES,
  SFX_FILES,
}
`
}

// записывает сгенерированный файл
const writeGeneratedFile = (content) => {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), {recursive: true})
  fs.writeFileSync(OUTPUT_FILE, content)
}

// выводит результат генерации в консоль
const logSoundData = ({musicPlayerFiles, sfxFiles}) => {
  console.log(`AUTOGENERATED SOUND LIST
  MUSIC PLAYER FILES: ${musicPlayerFiles.length}
  SFX FILES: ${sfxFiles.length}`)
}

// генерирует soundList файл
const generateSoundList = async () => {
  const soundData = collectSoundData()
  const content = createSoundListContent(soundData)
  const prettierConfig = await resolveConfig(OUTPUT_FILE)
  const formattedContent = await format(content, {...prettierConfig, filepath: OUTPUT_FILE})

  writeGeneratedFile(formattedContent)
  logSoundData(soundData)
}

export {generateSoundList}
